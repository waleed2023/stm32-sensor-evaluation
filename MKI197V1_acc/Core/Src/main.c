/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the System Power */
  SystemPower_Config();

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ICACHE_Init();
  MX_I2C2_Init();
  //scan_i2c_bus(&hi2c2);

  LSM6DSOX_Init(&hi2c2);
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  Enable_ITM_Trace();
  // <--- WICHTIG!

  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED_GREEN);
  BSP_LED_Init(LED_BLUE);
  BSP_LED_Init(LED_RED);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  // basis für Winkel
  HAL_Delay(1000);
  float base_pitch = 0.0f;
  int16_t ax, ay, az;
  if (LSM6DSOX_ReadAccel(&hi2c2, &ax, &ay, &az) == HAL_OK) {
      base_pitch = Calculate_Pitch(ax, ay, az);
      printf("Basiswinkel gesetzt: %.2f°\r\n", base_pitch);
  } else {
      printf("Fehler beim Lesen des Basiswinkels!\r\n");
  }
  while (1)
  {
	    int16_t ax, ay, az;
	    if (LSM6DSOX_ReadAccel(&hi2c2, &ax, &ay, &az) == HAL_OK)
	    {
	        float pitch = Calculate_Pitch(ax, ay, az);
	        float delta = pitch - base_pitch;

	        printf("Pitch: %.2f°, Delta: %.2f°\r\n", pitch, delta);

	        if (delta > 30.0f) {
	            printf("Arm gehoben\n");
	            BSP_LED_On(LED_GREEN);
	            BSP_LED_Off(LED_RED);
	        }
	        else if (delta < -30.0f) {
	            printf("Arm gesenkt\n");
	            BSP_LED_On(LED_RED);
	            BSP_LED_Off(LED_GREEN);
	        }
	        else {
	            printf("Arm ruhig\n");
	            BSP_LED_Off(LED_GREEN);
	            BSP_LED_Off(LED_RED);
	        }
	    }
	    else
	    {
	        printf("I2C Fehler\r\n");
	        BSP_LED_Toggle(LED_RED);
	    }
	    HAL_Delay(200);  // 5 Hz Abtastrate

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

